-- Consolidate nine function-specific operators into department roles (ADR 0018).
-- Memberships are copied before the function roles are removed; USER and ADMIN stay untouched.
INSERT INTO identity_roles (id, code) VALUES
    ('00000000-0000-0000-0000-000000000014', 'ACADEMIC_AFFAIRS'),
    ('00000000-0000-0000-0000-000000000015', 'CAMPUS_SERVICES'),
    ('00000000-0000-0000-0000-000000000016', 'FINANCE'),
    ('00000000-0000-0000-0000-000000000017', 'AUDITOR');

INSERT INTO identity_user_roles (user_id, role_id)
SELECT DISTINCT membership.user_id, replacement.id
FROM identity_user_roles membership
JOIN identity_roles previous ON previous.id = membership.role_id
JOIN identity_roles replacement ON replacement.code =
    CASE previous.code
        WHEN 'ORGANIZATION_ADMIN' THEN 'ACADEMIC_AFFAIRS'
        WHEN 'STUDENT_ADMIN' THEN 'ACADEMIC_AFFAIRS'
        WHEN 'PERSONNEL_ADMIN' THEN 'ACADEMIC_AFFAIRS'
        WHEN 'ACADEMIC_ADMIN' THEN 'ACADEMIC_AFFAIRS'
        WHEN 'DORMITORY_ADMIN' THEN 'CAMPUS_SERVICES'
        WHEN 'NOTIFICATION_ADMIN' THEN 'CAMPUS_SERVICES'
        WHEN 'EVENT_ADMIN' THEN 'CAMPUS_SERVICES'
        WHEN 'LIBRARY_ADMIN' THEN 'CAMPUS_SERVICES'
        WHEN 'FINANCE_ADMIN' THEN 'FINANCE'
        WHEN 'AUDIT_VIEWER' THEN 'AUDITOR'
        WHEN 'REPORTING_VIEWER' THEN 'AUDITOR'
    END
WHERE previous.code IN (
    'ORGANIZATION_ADMIN', 'STUDENT_ADMIN', 'PERSONNEL_ADMIN', 'ACADEMIC_ADMIN',
    'DORMITORY_ADMIN', 'NOTIFICATION_ADMIN', 'EVENT_ADMIN', 'LIBRARY_ADMIN',
    'FINANCE_ADMIN', 'AUDIT_VIEWER', 'REPORTING_VIEWER'
)
ON CONFLICT (user_id, role_id) DO NOTHING;

DELETE FROM identity_user_roles
WHERE role_id IN (
    SELECT id FROM identity_roles WHERE code IN (
        'ORGANIZATION_ADMIN', 'STUDENT_ADMIN', 'PERSONNEL_ADMIN', 'ACADEMIC_ADMIN',
        'DORMITORY_ADMIN', 'NOTIFICATION_ADMIN', 'EVENT_ADMIN', 'LIBRARY_ADMIN',
        'FINANCE_ADMIN', 'AUDIT_VIEWER', 'REPORTING_VIEWER'
    )
);

DELETE FROM identity_roles WHERE code IN (
    'ORGANIZATION_ADMIN', 'STUDENT_ADMIN', 'PERSONNEL_ADMIN', 'ACADEMIC_ADMIN',
    'DORMITORY_ADMIN', 'NOTIFICATION_ADMIN', 'EVENT_ADMIN', 'LIBRARY_ADMIN',
    'FINANCE_ADMIN', 'AUDIT_VIEWER', 'REPORTING_VIEWER'
);
